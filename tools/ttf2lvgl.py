#!/usr/bin/env python3
"""Convert a TTF into an LVGL 8 bitmap font (.c), 4 bits per pixel, tabular digits, using Pillow/FreeType.

usage: ttf2lvgl.py FONT.ttf SIZE NAME CHARS OUT.c
  CHARS: literal characters to include, e.g. "0123456789: " (sorted & deduplicated)
"""
import sys
from PIL import ImageFont


def main():
    path, size, name, chars, out = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4], sys.argv[5]
    font = ImageFont.truetype(path, size)
    ascent, _ = font.getmetrics()
    cps = sorted(set(ord(c) for c in chars))

    bitmap = bytearray()
    glyphs = []  # (bitmap_index, adv_w, w, h, ofs_x, ofs_y, cp)
    top_max, bot_max = 0, 0
    for cp in cps:
        ch = chr(cp)
        adv = round(font.getlength(ch) * 16)
        mask, (ox, oy) = font.getmask2(ch, mode="L")
        w, h = mask.size
        bbox = None
        if w and h:
            from PIL import Image
            img = Image.frombytes("L", (w, h), bytes(mask))
            bbox = img.getbbox()
        if not bbox:
            glyphs.append((len(bitmap), adv, 0, 0, 0, 0, cp))
            continue
        img = img.crop(bbox)
        x0, y0 = ox + bbox[0], oy + bbox[1]
        w, h = img.size
        ofs_y = ascent - (y0 + h)
        top_max = max(top_max, ofs_y + h)
        bot_max = max(bot_max, -ofs_y)
        px = [min(15, (v + 8) >> 4) for v in img.tobytes()]
        if len(px) % 2:
            px.append(0)
        start = len(bitmap)
        for i in range(0, len(px), 2):  # pixels packed continuously, high nibble first
            bitmap.append((px[i] << 4) | px[i + 1])
        glyphs.append((start, adv, w, h, x0, ofs_y, cp))

    # tabular digits: same advance for 0-9 so clocks/countdowns don't jiggle
    digit = [i for i, g in enumerate(glyphs) if 0x30 <= g[6] <= 0x39]
    if digit:
        mx = max(glyphs[i][1] for i in digit)
        for i in digit:
            bi, adv, w, h, ox, oy, cp = glyphs[i]
            glyphs[i] = (bi, mx, w, h, ox + round((mx - adv) / 32), oy, cp)

    # cmap ranges of consecutive code points
    ranges = []
    for gid, cp in enumerate(cps, start=1):
        if ranges and cp == ranges[-1][0] + ranges[-1][1]:
            ranges[-1][1] += 1
        else:
            ranges.append([cp, 1, gid])

    line_height = top_max + bot_max + 2
    base_line = bot_max + 1

    o = [f"/* {name}: generated by tools/ttf2lvgl.py from {path.split('/')[-1]} at {size}px, 4bpp */",
         '#include "lvgl.h"', "",
         f"static LV_ATTRIBUTE_LARGE_CONST const uint8_t {name}_bitmap[] = {{"]
    for i in range(0, len(bitmap), 24):
        o.append("    " + ", ".join(f"0x{b:02x}" for b in bitmap[i:i + 24]) + ",")
    o.append("};\n")
    o.append(f"static const lv_font_fmt_txt_glyph_dsc_t {name}_glyphs[] = {{")
    o.append("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},")
    for (bi, adv, w, h, ox, oy, cp) in glyphs:
        o.append(f"    {{.bitmap_index = {bi}, .adv_w = {adv}, .box_w = {w}, .box_h = {h}, "
                 f".ofs_x = {ox}, .ofs_y = {oy}}}, /* U+{cp:04X} */")
    o.append("};\n")
    o.append(f"static const lv_font_fmt_txt_cmap_t {name}_cmaps[] = {{")
    for (start, length, gid) in ranges:
        o.append(f"    {{.range_start = {start}, .range_length = {length}, .glyph_id_start = {gid}, "
                 ".unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, "
                 ".type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},")
    o.append("};\n")
    o.append(f"static lv_font_fmt_txt_glyph_cache_t {name}_cache;")
    o.append(f"""static const lv_font_fmt_txt_dsc_t {name}_dsc = {{
    .glyph_bitmap = {name}_bitmap,
    .glyph_dsc = {name}_glyphs,
    .cmaps = {name}_cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = {len(ranges)},
    .bpp = 4,
    .kern_classes = 0,
    .bitmap_format = 0,
    .cache = &{name}_cache,
}};

const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {line_height},
    .base_line = {base_line},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -2,
    .underline_thickness = 1,
    .dsc = &{name}_dsc,
}};
""")
    with open(out, "w") as f:
        f.write("\n".join(o))
    print(f"{out}: {len(cps)} glyphs, {len(bitmap)} bytes, line_height {line_height}")


if __name__ == "__main__":
    main()
